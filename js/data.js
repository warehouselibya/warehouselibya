// دالة لجلب عناصر الشرائح الدوارة مع دعم التصفية
function getCarouselSlides(filter = "products") {
    const newProducts = getLatestNewProducts(8);
    const news = LATEST_NEWS_DATA;

    if (filter === "news") {
        return news;
    } else if (filter === "all") {
        const merged = [];
        const maxLen = Math.max(news.length, newProducts.length);
        for (let i = 0; i < maxLen; i++) {
            if (i < news.length) merged.push(news[i]);
            if (i < newProducts.length) merged.push(newProducts[i]);
        }
        return merged;
    }

    return newProducts;
}